-- Shops and who works in them. A shop is created by its owner during registration (status DRAFT), then visited and
-- approved by the field team (next PR). Every change to a shop or a membership is also kept in the *_aud history
-- tables (Hibernate Envers), together with who made it (revinfo).

-- Shop codes are plain numbers starting at 1001, given out by the database so two shops can never get the same one.
CREATE SEQUENCE shop_code_seq START WITH 1001;

CREATE TABLE shops (
    id            UUID          PRIMARY KEY,
    shop_code     BIGINT        NOT NULL UNIQUE DEFAULT nextval('shop_code_seq'),   -- 1001, 1002, ...
    name          VARCHAR(100)  NOT NULL,
    owner_name    VARCHAR(100)  NOT NULL,
    address_line  VARCHAR(200)  NOT NULL,
    area          VARCHAR(100)  NOT NULL,                 -- society or locality
    city          VARCHAR(60)   NOT NULL,
    pincode       VARCHAR(6)    NOT NULL CHECK (pincode ~ '^[1-9][0-9]{5}$'),
    -- The shop's GPS pin; inside India's bounding box. Used for the 5 km customer radius.
    latitude      NUMERIC(9,6)  NOT NULL CHECK (latitude BETWEEN 6 AND 37.6),
    longitude     NUMERIC(9,6)  NOT NULL CHECK (longitude BETWEEN 68 AND 97.5),
    gstin         VARCHAR(15),                            -- optional
    udyam_number  VARCHAR(19),                            -- optional, e.g. UDYAM-TS-02-0012345
    status        VARCHAR(20)   NOT NULL CHECK (status IN ('DRAFT', 'PENDING_VISIT', 'APPROVED', 'SUSPENDED')),
    version       BIGINT        NOT NULL,                 -- optimistic locking: a stale edit is refused
    created_at    TIMESTAMPTZ   NOT NULL,
    updated_at    TIMESTAMPTZ   NOT NULL
);

-- The sequence belongs to this column: database tools show the link, and dropping the column drops the sequence
ALTER SEQUENCE shop_code_seq OWNED BY shops.shop_code;

CREATE TABLE shop_members (
    id          UUID         PRIMARY KEY,
    shop_id     UUID         NOT NULL REFERENCES shops (id),
    user_id     UUID         NOT NULL REFERENCES users (id),
    role        VARCHAR(10)  NOT NULL CHECK (role IN ('OWNER', 'HELPER')),
    created_at  TIMESTAMPTZ  NOT NULL,
    CONSTRAINT ux_shop_members_user UNIQUE (user_id)                 -- one shop per person (for now)
);

CREATE INDEX ix_shop_members_shop ON shop_members (shop_id);
-- Exactly one owner per shop. Note for ownership transfer (helpers PR): a partial unique index can't be deferred,
-- so demote the old owner and flush before promoting the new one.
CREATE UNIQUE INDEX ux_shop_members_one_owner ON shop_members (shop_id) WHERE role = 'OWNER';

-- Envers: one row per saved change (a "revision"), with when and by whom
CREATE TABLE revinfo (
    rev       BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revtstmp  BIGINT  NOT NULL,                           -- milliseconds since 1970 (UTC)
    user_id   UUID                                        -- who made the change; null for system jobs
);

-- Every version of every shop. revtype: 0 created, 1 changed, 2 deleted.
CREATE TABLE shops_aud (
    id            UUID          NOT NULL,
    rev           BIGINT        NOT NULL REFERENCES revinfo (rev),
    revtype       SMALLINT,
    shop_code     BIGINT,
    name          VARCHAR(100),
    owner_name    VARCHAR(100),
    address_line  VARCHAR(200),
    area          VARCHAR(100),
    city          VARCHAR(60),
    pincode       VARCHAR(6),
    latitude      NUMERIC(9,6),
    longitude     NUMERIC(9,6),
    gstin         VARCHAR(15),
    udyam_number  VARCHAR(19),
    status        VARCHAR(20),
    created_at    TIMESTAMPTZ,
    updated_at    TIMESTAMPTZ,
    PRIMARY KEY (id, rev)
);

CREATE TABLE shop_members_aud (
    id          UUID         NOT NULL,
    rev         BIGINT       NOT NULL REFERENCES revinfo (rev),
    revtype     SMALLINT,
    shop_id     UUID,
    user_id     UUID,
    role        VARCHAR(10),
    created_at  TIMESTAMPTZ,
    PRIMARY KEY (id, rev)
);

